"""Safe parsing and schema validation utilities for unstructured LLM outputs."""

import json
import re
from typing import TypeVar
from pydantic import BaseModel, ValidationError

from app.services.ai.schemas import StructuredExtractionResult

T = TypeVar("T", bound=BaseModel)

# Regex pattern for isolating markdown-fenced JSON blocks: ```json ... ``` or ``` ... ```
_MARKDOWN_JSON_PATTERN = re.compile(
    r"```(?:json)?\s*\n?([\s\S]*?)\n?```",
    re.IGNORECASE,
)


class SafeResponseParser:
    """Extracts, decodes, and structurally validates JSON from free-form model text.

    Protects downstream components when interacting with models (such as Nemotron 3 Ultra)
    that do not support hardware-enforced JSON schema output modes.

    Scope of validation:
    - Extracts candidate JSON from markdown-fenced blocks or raw prose.
    - Validates extracted JSON against a Pydantic schema (structure and type checking only).
    - Rejects responses that cannot be parsed or do not conform to the schema.
    - Returns explicit validation diagnostics; never raises unhandled exceptions.

    Scope limitations (by design):
    - Does NOT verify factual accuracy of AI-generated content.
    - Does NOT verify citations, quotations, or claims in model output.
    - Does NOT fabricate missing required fields.
    - Factual verification is a planned future stage (Step 9B+).
    """

    @staticmethod
    def extract_json_candidate(text: str) -> str | None:
        """Isolate potential JSON substrings from markdown blocks or raw text.

        Args:
            text: Raw string generated by the model.

        Returns:
            Candidate JSON string or None if no bracketed structure is found.
        """
        if not text or not text.strip():
            return None

        # 1. Check for markdown code fences first
        matches = _MARKDOWN_JSON_PATTERN.findall(text)
        for candidate in matches:
            trimmed = candidate.strip()
            if (trimmed.startswith("{") and trimmed.endswith("}")) or (
                trimmed.startswith("[") and trimmed.endswith("]")
            ):
                return trimmed

        # 2. Balanced bracket scan for outermost '{' ... '}'
        start_brace = text.find("{")
        end_brace = text.rfind("}")
        if start_brace != -1 and end_brace != -1 and end_brace > start_brace:
            return text[start_brace : end_brace + 1].strip()
        if start_brace != -1 and end_brace == -1:
            # Incomplete or truncated JSON object
            return text[start_brace:].strip()

        # 3. Balanced bracket scan for outermost '[' ... ']'
        start_bracket = text.find("[")
        end_bracket = text.rfind("]")
        if start_bracket != -1 and end_bracket != -1 and end_bracket > start_bracket:
            return text[start_bracket : end_bracket + 1].strip()
        if start_bracket != -1 and end_bracket == -1:
            # Incomplete or truncated JSON array
            return text[start_bracket:].strip()

        return None

    @classmethod
    def parse_model_output(
        cls,
        raw_text: str,
        target_schema: type[T],
    ) -> StructuredExtractionResult[T]:
        """Safely decode and validate LLM output into a target Pydantic model.

        Performs structural and type validation only.  Does NOT verify factual
        accuracy, citations, or quotations present in the model's text output.

        Guarantees:
        - Never silently fabricates missing required fields.
        - Returns explicit, typed validation failure states rather than raising
          unhandled exceptions.
        - Validation success (is_valid=True) means the response conforms to the
          target Pydantic schema; it does NOT mean the content is factually correct.

        Args:
            raw_text: Raw output string from completion choice.
            target_schema: Pydantic model class to validate against.

        Returns:
            StructuredExtractionResult[T] with either parsed_data or validation_error.
        """
        if not raw_text or not raw_text.strip():
            return StructuredExtractionResult[T](
                raw_text=raw_text or "",
                parsed_data=None,
                validation_error="Empty or whitespace response from model.",
                is_valid=False,
            )

        candidate = cls.extract_json_candidate(raw_text)
        if not candidate:
            return StructuredExtractionResult[T](
                raw_text=raw_text,
                parsed_data=None,
                validation_error="No JSON structure detected in model output.",
                is_valid=False,
            )

        try:
            parsed_json = json.loads(candidate)
        except json.JSONDecodeError as err:
            return StructuredExtractionResult[T](
                raw_text=raw_text,
                parsed_data=None,
                validation_error=f"JSON decoding error: {err.msg} at line {err.lineno} col {err.colno}",
                is_valid=False,
            )

        if not isinstance(parsed_json, dict):
            return StructuredExtractionResult[T](
                raw_text=raw_text,
                parsed_data=None,
                validation_error=f"Expected JSON object (dict) for {target_schema.__name__}, got {type(parsed_json).__name__}.",
                is_valid=False,
            )

        try:
            validated = target_schema.model_validate(parsed_json)
            return StructuredExtractionResult[T](
                raw_text=raw_text,
                parsed_data=validated,
                validation_error=None,
                is_valid=True,
            )
        except ValidationError as err:
            errors_summary = "; ".join(
                f"{'.'.join(str(loc) for loc in e['loc'])}: {e['msg']}"
                for e in err.errors()
            )
            return StructuredExtractionResult[T](
                raw_text=raw_text,
                parsed_data=None,
                validation_error=f"Schema validation failed: {errors_summary}",
                is_valid=False,
            )

"""Pydantic data models for AI integration and chat completions."""

from typing import Generic, Literal, TypeVar
from pydantic import BaseModel, ConfigDict, Field

T = TypeVar("T")


class ChatMessage(BaseModel):
    """A single chat message exchanged in a conversation."""

    role: Literal["system", "user", "assistant"] = Field(
        ...,
        description="Role of the message author",
    )
    content: str = Field(
        ...,
        description="Text content of the message",
    )

    model_config = ConfigDict(extra="ignore")


class ChatChoice(BaseModel):
    """An individual completion choice generated by the model."""

    index: int = Field(default=0, description="Index of the completion choice")
    message: ChatMessage = Field(..., description="Generated message object")
    finish_reason: str | None = Field(
        default=None,
        description="Reason the model stopped generating (e.g. 'stop', 'length')",
    )

    model_config = ConfigDict(extra="ignore")


class UsageInfo(BaseModel):
    """Token consumption statistics for a completion request."""

    prompt_tokens: int = Field(default=0, ge=0)
    completion_tokens: int = Field(default=0, ge=0)
    total_tokens: int = Field(default=0, ge=0)

    model_config = ConfigDict(extra="ignore")


class ChatCompletionRequest(BaseModel):
    """Standardized request envelope for AI chat completions."""

    model: str = Field(..., description="Model identifier to invoke")
    messages: list[ChatMessage] = Field(..., min_length=1, description="List of prompt messages")
    temperature: float = Field(
        default=0.2,
        ge=0.0,
        le=2.0,
        description="Sampling temperature (lower values enforce strict grounding)",
    )
    max_tokens: int | None = Field(
        default=None,
        ge=1,
        le=32768,
        description="Maximum tokens to generate",
    )
    top_p: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Nucleus sampling parameter",
    )

    model_config = ConfigDict(extra="ignore")


class ChatCompletionResponse(BaseModel):
    """Standardized response envelope from an AI chat completion."""

    id: str = Field(..., description="Unique completion identifier")
    model: str = Field(..., description="Actual model that generated the response")
    choices: list[ChatChoice] = Field(..., min_length=1, description="List of generated choices")
    usage: UsageInfo | None = Field(default=None, description="Token usage statistics if provided")

    model_config = ConfigDict(extra="ignore")

    @property
    def first_content(self) -> str:
        """Helper to extract text content of the primary completion choice."""
        if self.choices and self.choices[0].message:
            return self.choices[0].message.content
        return ""


class AIConfigStatus(BaseModel):
    """Safe status descriptor for AI provider integration and health inspection."""

    status: Literal["not_configured", "configured", "unavailable"] = Field(
        ...,
        description="Operational status of the AI integration",
    )
    provider: str = Field(
        default="openrouter",
        description="Name of the active AI provider",
    )
    model: str = Field(
        ...,
        description="Active model identifier",
    )
    base_url: str = Field(
        ...,
        description="Target API base endpoint URL",
    )
    is_free_tier: bool = Field(
        default=True,
        description="Whether the selected model is hosted under a free tier",
    )
    privacy_warning: str = Field(
        default=(
            "Free tier model endpoint active. NEVER transmit confidential, "
            "proprietary, or personally identifiable data (PII) to this model."
        ),
        description="Mandatory privacy guidance for active model tier",
    )

    model_config = ConfigDict(extra="ignore")


class StructuredExtractionResult(BaseModel, Generic[T]):
    """Generic envelope for structured response extraction and validation."""

    raw_text: str = Field(..., description="Raw string content returned by the model")
    parsed_data: T | None = Field(default=None, description="Parsed and validated Pydantic model")
    validation_error: str | None = Field(
        default=None,
        description="Error description if JSON decoding or schema validation failed",
    )
    is_valid: bool = Field(
        default=False,
        description=(
            "Whether the response parses and validates against the target Pydantic schema "
            "(structural and type validation only; does not verify factual accuracy, "
            "citations, or quotations in the model output)"
        ),
    )

    model_config = ConfigDict(extra="ignore")

